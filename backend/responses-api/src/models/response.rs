//! Response types for the Responses API.

use serde::{Deserialize, Serialize};
use serde_json::Value;

use super::{Tool, ToolChoice};

/// The response object returned by POST /v1/responses
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Response {
    /// Unique identifier for this response
    pub id: String,

    /// Always "response"
    pub object: &'static str,

    /// Unix timestamp of creation
    pub created_at: i64,

    /// Response status
    pub status: ResponseStatus,

    /// Error information if status is "failed"
    #[serde(skip_serializing_if = "Option::is_none")]
    pub error: Option<ResponseError>,

    /// Details about incomplete response
    #[serde(skip_serializing_if = "Option::is_none")]
    pub incomplete_details: Option<IncompleteDetails>,

    /// The instructions used
    #[serde(skip_serializing_if = "Option::is_none")]
    pub instructions: Option<String>,

    /// Max output tokens setting
    #[serde(skip_serializing_if = "Option::is_none")]
    pub max_output_tokens: Option<u32>,

    /// Model ID used
    pub model: String,

    /// Output items generated by the model (reasoning, messages, tool calls interleaved)
    pub output: Vec<OutputItem>,

    /// Whether parallel tool calls were enabled
    pub parallel_tool_calls: bool,

    /// Previous response ID if this was a continuation
    #[serde(skip_serializing_if = "Option::is_none")]
    pub previous_response_id: Option<String>,

    /// Reasoning configuration (for o-series models)
    #[serde(skip_serializing_if = "Option::is_none")]
    pub reasoning: Option<ReasoningConfig>,

    /// Whether this response is stored
    pub store: bool,

    /// Temperature used
    pub temperature: f32,

    /// Text format configuration
    #[serde(skip_serializing_if = "Option::is_none")]
    pub text: Option<TextConfig>,

    /// Tool choice setting used
    pub tool_choice: ToolChoice,

    /// Tools that were available
    pub tools: Vec<Tool>,

    /// Top-p value used
    pub top_p: f32,

    /// Truncation setting
    #[serde(default)]
    pub truncation: Truncation,

    /// Token usage statistics
    pub usage: Usage,

    /// User identifier (deprecated)
    #[serde(skip_serializing_if = "Option::is_none")]
    pub user: Option<String>,

    /// Metadata
    #[serde(default, skip_serializing_if = "Value::is_null")]
    pub metadata: Value,
}

impl Response {
    pub const OBJECT: &'static str = "response";
}

/// Response status.
#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum ResponseStatus {
    Completed,
    Failed,
    InProgress,
    Cancelled,
    Queued,
    Incomplete,
}

/// Error information for failed responses.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ResponseError {
    pub code: String,
    pub message: String,
}

/// Details about why a response is incomplete.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct IncompleteDetails {
    pub reason: IncompleteReason,
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum IncompleteReason {
    MaxOutputTokens,
    ContentFilter,
}

// ============================================================================
// Output Items - All possible types that can appear in response.output[]
// These can be interleaved: reasoning -> function_call -> message -> reasoning...
// ============================================================================

/// Output item in the response. Multiple types can be interleaved.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum OutputItem {
    /// Reasoning/thinking from the model (o-series, DeepSeek R1, etc.)
    Reasoning(ReasoningOutput),

    /// A message from the assistant
    Message(MessageOutput),

    /// A function call request from the model
    FunctionCall(FunctionCallOutput),

    /// A custom tool call (free-form input, not JSON schema)
    CustomToolCall(CustomToolCallOutput),

    /// Web search tool call (built-in)
    WebSearchCall(WebSearchCallOutput),

    /// File search tool call (built-in)
    FileSearchCall(FileSearchCallOutput),

    /// Code interpreter tool call (built-in)
    CodeInterpreterCall(CodeInterpreterCallOutput),

    /// Computer use tool call (built-in)
    ComputerCall(ComputerCallOutput),
}

// ============================================================================
// Reasoning Output
// ============================================================================

/// Reasoning/thinking output from the model.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ReasoningOutput {
    /// Unique ID for this reasoning item
    pub id: String,
    /// Status of this output item
    #[serde(default)]
    pub status: OutputStatus,
    /// Reasoning content (may be empty if hidden)
    #[serde(default)]
    pub content: Vec<ReasoningContent>,
    /// Summary of reasoning (if available)
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub summary: Vec<ReasoningSummary>,
    /// Encrypted content for multi-turn (when using store=false)
    #[serde(skip_serializing_if = "Option::is_none")]
    pub encrypted_content: Option<String>,
}

/// Content within reasoning output.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum ReasoningContent {
    /// Visible reasoning text
    ReasoningText { text: String },
    /// Redacted reasoning (for hidden chain-of-thought)
    Redacted {},
}

/// Summary of reasoning.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum ReasoningSummary {
    SummaryText { text: String },
}

// ============================================================================
// Message Output
// ============================================================================

/// A message output from the assistant.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MessageOutput {
    /// Unique ID for this message
    pub id: String,
    /// Status of this output item
    pub status: OutputStatus,
    /// Always "assistant"
    pub role: OutputRole,
    /// Content of the message
    pub content: Vec<OutputContent>,
}

/// Content within a message output.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum OutputContent {
    /// Text output
    OutputText {
        text: String,
        #[serde(default, skip_serializing_if = "Vec::is_empty")]
        annotations: Vec<Annotation>,
    },
    /// Refusal (content policy violation)
    Refusal { refusal: String },
}

/// Annotation on text output (citations, file references, etc.)
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum Annotation {
    FileCitation {
        file_id: String,
        #[serde(skip_serializing_if = "Option::is_none")]
        filename: Option<String>,
        index: u32,
    },
    UrlCitation {
        url: String,
        #[serde(skip_serializing_if = "Option::is_none")]
        title: Option<String>,
        index: u32,
    },
    FilePath {
        file_id: String,
        index: u32,
    },
}

// ============================================================================
// Function Call Output
// ============================================================================

/// A function call output from the model.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FunctionCallOutput {
    /// Unique ID for this function call item
    pub id: String,
    /// Call ID to reference when sending results back
    pub call_id: String,
    /// Name of the function to call
    pub name: String,
    /// JSON-encoded arguments
    pub arguments: String,
    /// Status of this output item
    pub status: OutputStatus,
}

// ============================================================================
// Custom Tool Call Output (free-form input)
