/// Custom tool call with free-form text input (not JSON schema).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CustomToolCallOutput {
    /// Unique ID for this item
    pub id: String,
    /// Call ID to reference when sending results back
    pub call_id: String,
    /// Name of the custom tool
    pub name: String,
    /// Free-form text input (not JSON)
    pub input: String,
    /// Status of this output item
    pub status: OutputStatus,
}

// ============================================================================
// Built-in Tool Outputs
// ============================================================================

/// Web search tool call output.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct WebSearchCallOutput {
    pub id: String,
    pub status: OutputStatus,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub action: Option<WebSearchAction>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct WebSearchAction {
    pub query: String,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub sources: Vec<WebSearchSource>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct WebSearchSource {
    pub url: String,
    pub title: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub snippet: Option<String>,
}

/// File search tool call output.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FileSearchCallOutput {
    pub id: String,
    pub status: OutputStatus,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub results: Vec<FileSearchResult>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FileSearchResult {
    pub file_id: String,
    pub filename: String,
    pub score: f32,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub text: Option<String>,
}

/// Code interpreter tool call output.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CodeInterpreterCallOutput {
    pub id: String,
    pub status: OutputStatus,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub code: Option<String>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub outputs: Vec<CodeInterpreterOutput>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum CodeInterpreterOutput {
    Logs { logs: String },
    Image { file_id: String },
}

/// Computer use tool call output.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ComputerCallOutput {
    pub id: String,
    pub status: OutputStatus,
    pub action: ComputerAction,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub call_id: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub pending_safety_checks: Option<Vec<SafetyCheck>>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum ComputerAction {
    Click {
        x: i32,
        y: i32,
        button: String,
    },
    DoubleClick {
        x: i32,
        y: i32,
    },
    Move {
        x: i32,
        y: i32,
    },
    Drag {
        path: Vec<CoordinatePair>,
    },
    Scroll {
        x: i32,
        y: i32,
        direction: String,
        amount: i32,
    },
    Keypress {
        keys: Vec<String>,
    },
    Type {
        text: String,
    },
    Screenshot {},
    Wait {
        ms: u32,
    },
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CoordinatePair {
    pub x: i32,
    pub y: i32,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SafetyCheck {
    pub id: String,
    pub code: String,
    pub message: String,
}

